    mov r10b,cl
    and cl,7         ; index % 8
    test cl,cl
    jz skip_rot
rot_loop:
    rol al,1
    dec cl
    jnz rot_loop
skip_rot:
    mov cl,r10b

    ; XOR with position-dependent key: (cl * 7 + 0x5A) & 0xFF
    mov bl,cl
    shl bl,3        ; bl = 8*cl
    sub bl,cl       ; bl = 7*cl
    add bl,0x5A
    xor al,bl

