    jne fail
    cmp byte [buf+2],'M'
    jne fail
    cmp byte [buf+3],'{'
    jne fail

    xor r8b,r8b      ; checksum_1
    xor r9b,r9b      ; checksum_2
    xor rcx,rcx      ; index

