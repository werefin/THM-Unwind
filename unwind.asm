; Decode function: rsi=encoded string, rdx=length, rdi=output buffer
; Decodes in-place using XOR with rotating key: 0xAA ^ (index & 0xFF)
decode:
    push rcx
    push rdi
    push rbx
    mov rdi,rsi        ; decode in-place
    mov rcx,rdx
    xor rbx,rbx        ; index counter
decode_loop:
    mov al,0xAA
    xor al,bl          ; key = 0xAA ^ (index & 0xFF), bl is low byte of rbx
    xor byte [rdi],al
    inc rdi
    inc rbx
    dec rcx
    jnz decode_loop
    pop rbx
    pop rdi
    pop rcx
    ret

