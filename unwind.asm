    add rax,4        ; rax = 4 + 16 = 20 (offset for '}')
    cmp rax,r11      ; compare with bytes read
    jge fail         ; if offset >= bytes read, fail (out of bounds)
    
    mov al,[buf+4+rcx]
    cmp al,'}'
    jne fail

